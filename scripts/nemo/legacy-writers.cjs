#!/usr/bin/env node
'use strict';
// CS4b (#2364): generate the legacy-writer wrap lists and the desktop-admitted kinds from
// engineering/application/legacy-writer-families.json. `--check` fails on drift, on an
// undeclared or stale n20 guard kind, and on an invalid declaration.
const fs = require('node:fs');
const path = require('node:path');

const DECLARATION = 'engineering/application/legacy-writer-families.json';
const CAPABILITIES = 'engineering/application/capabilities-v2';
const OPERATIONS = 'src/js/application/native-opacity-operations.js';
const SURFACE = 'src/js/adapters/native-opacity-legacy-surface.js';
const GUARD_SOURCES = ['src/js/app.js', 'src/js/motion.js', 'src/js/timeline.js', 'src/js/tweens.js', 'src/js/project.js'];
const TARGETS = ['global', 'timeline', 'motion', 'script', 'plugin'];
const AUTHORITIES = ['legacy-owned', 'native', 'unavailable'];
const SPECIAL_KINDS = ['boot-scaffold'];

function fail(message) { throw new Error(`legacy-writers: ${message}`); }

function validate(doc, root) {
  if (!doc || doc.schema !== 'nemo.legacy-writer-families/1') fail('unsupported schema');
  if (!Array.isArray(doc.families) || !doc.families.length) fail('families must be a non-empty array');
  for (const target of TARGETS) if (typeof (doc.prefixes || {})[target] !== 'string') fail(`missing prefix for ${target}`);
  const families = new Set(), names = new Map(), kinds = new Map();
  for (const family of doc.families) {
    if (!family || typeof family.family !== 'string' || families.has(family.family)) fail(`duplicate or invalid family ${family && family.family}`);
    families.add(family.family);
    if (!AUTHORITIES.includes(family.authority)) fail(`${family.family}: unknown authority ${family.authority}`);
    if (family.authority === 'native') {
      if (typeof family.capability !== 'string') fail(`${family.family}: a native family names its capability`);
      if (!fs.existsSync(path.join(root, CAPABILITIES, `${family.capability}.json`))) fail(`${family.family}: unknown capability ${family.capability}`);
    }
    for (const [target, list] of Object.entries(family.entries || {})) {
      if (!TARGETS.includes(target)) fail(`${family.family}: unknown target ${target}`);
      if (!Array.isArray(list)) fail(`${family.family}: entries.${target} must be an array`);
      for (const name of list) {
        const key = `${target}:${name}`;
        if (typeof name !== 'string' || !/^[A-Za-z_$][\w$]*$/.test(name) || names.has(key)) fail(`duplicate or invalid entry ${key}`);
        names.set(key, family.family);
      }
    }
    for (const kind of family.kinds || []) {
      if (typeof kind !== 'string' || !/^[a-z0-9-]+$/.test(kind) || kinds.has(kind) || SPECIAL_KINDS.includes(kind)) fail(`duplicate or invalid kind ${kind}`);
      kinds.set(kind, family.family);
    }
  }
  return { names, kinds };
}

// Visibility keeps its bounded native route; its generic guard is only the fallback.
function plan(doc) {
  const wraps = TARGETS.map((target) => [target, doc.prefixes[target], []]);
  let visibility = [];
  for (const family of doc.families) {
    for (const [target, list] of Object.entries(family.entries || {})) {
      if (family.family === 'layer-visibility') { visibility = visibility.concat(list); continue; }
      wraps.find((entry) => entry[0] === target)[2].push(...list);
    }
  }
  const admitted = [];
  for (const family of doc.families) {
    if (family.authority !== 'legacy-owned') continue;
    admitted.push(...(family.kinds || []));
    for (const [target, list] of Object.entries(family.entries || {})) admitted.push(...list.map((name) => doc.prefixes[target] + name));
  }
  return { wraps: wraps.filter((entry) => entry[2].length), visibility, admitted: admitted.sort() };
}

function list(values, indent) {
  const lines = [], width = 100;
  let line = '';
  for (const value of values.map((v) => `'${v}'`)) {
    if (line && (indent + line + ', ' + value).length > width) { lines.push(line + ','); line = value; } else line = line ? `${line}, ${value}` : value;
  }
  if (line) lines.push(line);
  return lines.map((l) => indent + l).join('\n');
}

const HEADER = `generated by scripts/nemo/legacy-writers.cjs from ${DECLARATION}; do not edit`;
function region(name, body) { return `// <generated:${name}> ${HEADER}\n${body}\n  // </generated:${name}>`; }
function operationsRegion(p) {
  const wraps = p.wraps.map(([target, prefix, names]) => `    ['${target}', '${prefix}', [\n${list(names, '      ')}\n    ]]`).join(',\n');
  return region('legacy-writer-wraps', `  var LEGACY_WRAPS = Object.freeze([\n${wraps}\n  ]);\n  var LEGACY_VISIBILITY_FALLBACK = Object.freeze([${p.visibility.map((n) => `'${n}'`).join(', ')}]);`);
}
function surfaceRegion(p) {
  return region('legacy-writer-kinds', `  var DESKTOP_LEGACY_KINDS = Object.freeze([${p.admitted.length ? '\n' + list(p.admitted, '    ') + '\n  ' : ''}]);`);
}
function splice(source, name, replacement, file) {
  const start = source.indexOf(`// <generated:${name}>`), endTag = `// </generated:${name}>`, end = source.indexOf(endTag);
  if (start < 0 || end < start) fail(`${file} has no generated:${name} region`);
  return source.slice(0, start) + replacement + source.slice(end + endTag.length);
}

function guardKinds(root) {
  const found = new Set();
  for (const file of GUARD_SOURCES) {
    for (const match of fs.readFileSync(path.join(root, file), 'utf8').matchAll(/n20[A-Za-z]*\(['"]([a-z0-9-]+)['"]/g)) found.add(match[1]);
  }
  return found;
}

function build(root, doc) {
  const declared = validate(doc, root), p = plan(doc), used = guardKinds(root);
  for (const kind of used) if (!declared.kinds.has(kind) && !SPECIAL_KINDS.includes(kind)) fail(`guard kind ${kind} is not declared in ${DECLARATION}`);
  for (const kind of declared.kinds.keys()) if (!used.has(kind)) fail(`declared kind ${kind} has no guard call site`);
  const read = (file) => fs.readFileSync(path.join(root, file), 'utf8');
  return {
    plan: p,
    files: {
      [OPERATIONS]: splice(read(OPERATIONS), 'legacy-writer-wraps', operationsRegion(p), OPERATIONS),
      [SURFACE]: splice(read(SURFACE), 'legacy-writer-kinds', surfaceRegion(p), SURFACE),
    },
  };
}

function run(argv, root = path.resolve(__dirname, '../..')) {
  const doc = JSON.parse(fs.readFileSync(path.join(root, DECLARATION), 'utf8'));
  const result = build(root, doc), check = argv.includes('--check');
  const stale = Object.entries(result.files).filter(([file, text]) => fs.readFileSync(path.join(root, file), 'utf8') !== text).map(([file]) => file);
  if (check) {
    if (stale.length) fail(`generated regions are stale in ${stale.join(', ')}; run node scripts/nemo/legacy-writers.cjs`);
    return `legacy writers current (${doc.families.length} families, ${result.plan.admitted.length} desktop-admitted kinds)`;
  }
  for (const file of stale) fs.writeFileSync(path.join(root, file), result.files[file]);
  return `legacy writers written (${stale.length} file(s) changed)`;
}

if (require.main === module) {
  try { console.log(run(process.argv.slice(2))); } catch (error) { console.error(error.message); process.exitCode = 1; }
}
module.exports = { validate, plan, build, run, DECLARATION };
