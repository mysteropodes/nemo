use crate::evaluation::expression_controls::{
    control_frame, find_control, layer_control, normalize_control_name, resolve_control_layer,
    self_control, shape_value, ControlDecl, ControlError, ControlValue, LayerIds,
};
use serde_json::Value;
use std::cell::Cell;

/// Bit pattern for comparison, with every NaN folded to one value; -0 and
/// +0 stay distinct.
fn bits(x: f64) -> u64 {
    if x.is_nan() {
        f64::NAN.to_bits()
    } else {
        x.to_bits()
    }
}

fn hex(v: &Value) -> f64 {
    let h = v.as_str().expect("hex string");
    f64::from_bits(u64::from_str_radix(h, 16).expect("hex bits"))
}

fn opt_hex(v: &Value) -> Option<f64> {
    (!v.is_null()).then(|| hex(v))
}

fn opt_str(v: &Value) -> Option<&str> {
    v.as_str()
}

/// One stub layer: ids, controls (`None` when `exprControls` is not an
/// array) and the oracle's stub track bases.
struct Layer<'a> {
    ids: LayerIds<'a>,
    controls: Vec<ControlDecl<'a>>,
    bases: Vec<Vec<f64>>,
}

fn layers(v: &Value) -> Vec<Layer<'_>> {
    v.as_array()
        .expect("layers")
        .iter()
        .map(|l| {
            let list = l["controls"].as_array().map(Vec::as_slice).unwrap_or(&[]);
            Layer {
                ids: LayerIds {
                    uid: opt_str(&l["uid"]),
                    name: opt_str(&l["name"]),
                },
                controls: list
                    .iter()
                    .map(|c| ControlDecl {
                        key: c["key"].as_str().expect("key"),
                        name: opt_str(&c["name"]),
                    })
                    .collect(),
                bases: list
                    .iter()
                    .map(|c| {
                        c["base"]
                            .as_array()
                            .expect("base")
                            .iter()
                            .map(hex)
                            .collect()
                    })
                    .collect(),
            }
        })
        .collect()
}

/// The oracle's stub track: component `i` is `base[i] + frame * (i + 1)`.
fn track(layer: &Layer<'_>, key: &str, frame: f64) -> Vec<f64> {
    let at = layer
        .controls
        .iter()
        .position(|c| c.key == key)
        .expect("sampled key is declared");
    layer.bases[at]
        .iter()
        .enumerate()
        .map(|(i, b)| b + frame * (i as f64 + 1.0))
        .collect()
}

/// The JavaScript message the stubbed `SM.t` produces for an error.
/// It embeds `String(ref)` or `String(name)`.
fn message(err: ControlError, row: &Value) -> String {
    let shown = |subject: &str, undefined_flag: &str| {
        if row[undefined_flag].as_bool() == Some(true) {
            "undefined".to_owned()
        } else {
            row[subject].as_str().unwrap_or("null").to_owned()
        }
    };
    let (prefix, suffix, shown) = match err {
        ControlError::UnknownLayer => (
            "exprErrorUnknownLayerPrefix",
            "exprErrorUnknownLayerSuffix",
            shown("ref", "refUndefined"),
        ),
        ControlError::UnknownControl => (
            "exprErrorUnknownControlPrefix",
            "exprErrorUnknownControlSuffix",
            shown("name", "nameUndefined"),
        ),
        ControlError::NoLayer => return "<exprErrorControlNoLayer>".to_owned(),
    };
    format!("<{prefix}>{shown}<{suffix}>")
}

fn check(row: &Value, label: &str, got: Result<ControlValue, ControlError>, sampled: Option<f64>) {
    if let Some(err) = row.get("err") {
        let e = got.expect_err(label);
        assert_eq!(message(e, row), err.as_str().expect("err"), "{label}");
        return;
    }
    let ok = &row["ok"];
    match (got.expect(label), ok.get("s"), ok.get("v")) {
        (ControlValue::Scalar(x), Some(s), None) => assert_eq!(bits(x), bits(hex(s)), "{label}"),
        (ControlValue::Vector(v), None, Some(e)) => {
            let e: Vec<u64> = e
                .as_array()
                .expect("v")
                .iter()
                .map(|x| bits(hex(x)))
                .collect();
            assert_eq!(v.iter().map(|&x| bits(x)).collect::<Vec<_>>(), e, "{label}");
        }
        (got, _, _) => panic!("{label}: shape {got:?}"),
    }
    assert_eq!(
        sampled.map(bits),
        opt_hex(&row["sampled"]).map(bits),
        "{label}: sampled frame"
    );
}

// Generated by `oracle-gen/controls.mjs` from the verbatim functions of
// `src/js/motion.js` at `codex/native-remediation`
// 660ac5ef79f9a1da54cfabbe5279aeb76a941f73 (Node 22 / V8) against a stub
// `valueAtFrame` whose control component `i` is `base[i] + frame * (i+1)`
// and an `SM.t` that returns `<key>`. One JSON object per line; numbers are
// IEEE 754 bit patterns in hex.
const ORACLE: &str = include_str!("fixtures/expression-controls/oracle.jsonl");

#[test]
fn generated_oracle_matches_javascript() {
    let (mut rows, mut values, mut errors) = (0, 0, 0);
    for (line_no, line) in ORACLE.lines().enumerate() {
        let row: Value = serde_json::from_str(line).expect("json row");
        let label = format!("oracle line {}", line_no + 1);
        let sampled = Cell::new(None);
        let name = opt_str(&row["name"]);
        match row["op"].as_str().expect("op") {
            "norm" => {
                assert_eq!(
                    normalize_control_name(name),
                    row["out"].as_str().expect("out"),
                    "{label}"
                );
            }
            "layer" => {
                let ls = layers(&row["layers"]);
                let ids: Vec<LayerIds<'_>> = ls.iter().map(|l| l.ids).collect();
                let got = layer_control(
                    &ids,
                    |i| &ls[i].controls,
                    opt_str(&row["ref"]),
                    name,
                    opt_hex(&row["frame"]),
                    opt_hex(&row["ctx"]),
                    hex(&row["current"]),
                    |i, key, f| {
                        sampled.set(Some(f));
                        track(&ls[i], key, f)
                    },
                );
                check(&row, &label, got, sampled.get());
            }
            "self" => {
                let ls = layers(&row["layers"]);
                let own = row["self"].as_u64().map(|i| &ls[i as usize]);
                let got = self_control(
                    opt_hex(&row["ctx"]),
                    own.map(|l| l.controls.as_slice()),
                    name,
                    opt_hex(&row["frame"]),
                    |key, f| {
                        sampled.set(Some(f));
                        track(own.expect("sampled layer"), key, f)
                    },
                );
                check(&row, &label, got, sampled.get());
            }
            op => panic!("unknown oracle op {op}"),
        }
        if row.get("err").is_some() {
            errors += 1;
        } else if row.get("ok").is_some() {
            values += 1;
        }
        rows += 1;
    }
    assert_eq!(rows, 248, "oracle row count");
    assert!(values > 50 && errors > 50, "coverage {values}/{errors}");
}

#[test]
fn lookup_rules_match_the_characterized_javascript() {
    let ls = [
        LayerIds {
            uid: Some("Ctrl"),
            name: Some("Rig"),
        },
        LayerIds {
            uid: Some("u2"),
            name: Some("Ctrl"),
        },
        LayerIds {
            uid: Some(""),
            name: Some(""),
        },
    ];
    // A uid beats another layer's identical name; names resolve second.
    assert_eq!(resolve_control_layer(&ls, Some("Ctrl")), Some(0));
    assert_eq!(resolve_control_layer(&ls, Some("Rig")), Some(0));
    assert_eq!(resolve_control_layer(&ls, Some("u2")), Some(1));
    // Falsy references never match, even a layer whose ids are empty.
    assert_eq!(resolve_control_layer(&ls, Some("")), None);
    assert_eq!(resolve_control_layer(&ls, None), None);
    // Names are trimmed (JS whitespace set) and lower-cased; first wins.
    let cs = [
        ControlDecl {
            key: "a",
            name: Some("\u{FEFF}Turn"),
        },
        ControlDecl {
            key: "b",
            name: Some("turn"),
        },
        ControlDecl {
            key: "c",
            name: Some("\u{85}Lift"),
        },
    ];
    assert_eq!(find_control(&cs, Some(" TURN\t")).map(|c| c.key), Some("a"));
    assert_eq!(
        find_control(&cs, Some("lift")),
        None,
        "U+0085 is not JS trim"
    );
    assert_eq!(find_control(&cs, Some("   ")), None);
    assert_eq!(find_control(&cs, None), None);
    // Frames: an explicit argument goes through _num, -0 survives.
    assert_eq!(control_frame(Some(f64::NAN), Some(3.0), 7.0), 0.0);
    assert_eq!(bits(control_frame(Some(-0.0), Some(3.0), 7.0)), bits(-0.0));
    assert_eq!(control_frame(None, Some(3.0), 7.0), 3.0);
    assert_eq!(control_frame(None, None, 7.0), 7.0);
    // Shapes: one component is a number, none is an empty array.
    assert_eq!(shape_value(vec![2.0]), ControlValue::Scalar(2.0));
    assert_eq!(shape_value(Vec::new()), ControlValue::Vector(Vec::new()));
    // Outside an evaluation a self read is 0 and samples nothing.
    let got = self_control(None, None, Some("x"), None, |_, _| unreachable!());
    assert_eq!(got, Ok(ControlValue::Scalar(0.0)));
    assert_eq!(
        self_control(Some(1.0), None, Some("x"), None, |_, _| unreachable!()),
        Err(ControlError::NoLayer)
    );
}
