const TRIG_TOLERANCE: f64 = 1e-9;
const NAN: f64 = f64::NAN;
const BASE: ElementMotion = ElementMotion::from_values([5.0, -3.0, 10.0, 1.5, 0.5, 0.8, 2.0, -1.0]);

fn num(t: &str) -> f64 {
    t.parse().unwrap_or_else(|_| panic!("bad number {t:?}"))
}

fn opt(t: &str) -> Option<f64> {
    (t != "-").then(|| num(t))
}

fn nums(t: &str) -> Vec<f64> {
    t.split('_').map(num).collect()
}

fn stroke(t: &str) -> AnimatorStroke {
    let (ix, pts) = t.split_once('=').expect("stroke");
    let i: Vec<Option<f64>> = ix.split(',').map(opt).collect();
    let mut s = AnimatorStroke::default();
    [s.units.char_index, s.units.word_index, s.units.line_index] = [i[0], i[1], i[2]];
    for p in pts.split(';').filter(|p| *p != "~") {
        s.rest_points
            .push((p != "!").then(|| nums(p).try_into().expect("point")));
    }
    s
}

fn selector(t: &[&str]) -> Selector {
    let z = |s: &str| opt(s).unwrap_or(0.0);
    Selector {
        selector_type: SelectorType::from_baseline(t[0]),
        start: z(t[1]),
        end: opt(t[2]),
        offset: z(t[3]),
        units: Units::from_baseline(t[4]),
        based_on: BasedOn::from_baseline(t[5]),
        shape: z(t[6]),
        amount: opt(t[7]),
        ease_high: z(t[8]),
        ease_low: z(t[9]),
        smooth: opt(t[10]),
        wiggle_min: opt(t[11]),
        wiggle_max: opt(t[12]),
        wiggles_per_sec: opt(t[13]),
        correlation: opt(t[14]),
        seed: z(t[15]),
    }
}

fn props(t: &str) -> Option<AnimatorProps> {
    let mut p = AnimatorProps::default();
    match t {
        "~" => return None,
        "." => return Some(p),
        _ => {}
    }
    for kv in t.split(',') {
        let (k, v) = kv.split_once('=').expect("prop");
        let c: Vec<Option<f64>> = v.split('_').map(opt).collect();
        let color = || AnimatorColor {
            rgb: [c[0], c[1], c[2]].map(|x| x.expect("rgb")),
            alpha: c[3],
        };
        match k {
            "pos" => p.position = Some([c[0], c[1]]),
            "rot" => p.rotation = c[0],
            "scl" => p.scale = Some([c[0], c[1]]),
            "op" => p.opacity = c[0],
            "fc" => p.fill_color = Some(color()),
            "sc" => p.stroke_color = Some(color()),
            _ => panic!("prop {k}"),
        }
    }
    Some(p)
}

fn animator(t: &str) -> TextAnimator {
    let f: Vec<&str> = t.split(' ').collect();
    assert_eq!(f.len(), 18, "animator {t:?}");
    let (enabled, selector, props) = (f[0] == "y", selector(&f[1..17]), props(f[17]));
    TextAnimator {
        enabled,
        props,
        selector,
    }
}

fn join(v: &[f64]) -> String {
    v.iter().map(f64::to_string).collect::<Vec<_>>().join("_")
}

fn pull(p: &Option<ColorPull>) -> String {
    p.map_or("-".into(), |p| join(&p.values()))
}

/// The kernel's answer in the oracle's CONTRIB;FOLD layout.
fn encode(c: &Option<Contribution>, f: &Option<FoldedMotion>) -> String {
    let c = c.map_or("~".into(), |c| {
        let anchor = c.anchor.map_or("-".into(), |a| join(&a));
        let v = join(&[c.dx, c.dy, c.rot, c.sx, c.sy, c.op]);
        format!("{v}/{anchor}/{}/{}", pull(&c.fill), pull(&c.stroke))
    });
    let f = f.map_or("~".into(), |f| {
        let (fill, stroke) = (pull(&f.fill), pull(&f.stroke));
        format!("{}/{fill}/{stroke}", join(&f.motion.values()))
    });
    format!("{c};{f}")
}

/// Same layout (every absent field alike), numbers equal bit for bit or, on a
/// trig row, within the bound. Answers the largest deviation, `None` on a miss.
fn agree(got: &str, want: &str, trig: bool) -> Option<f64> {
    let split = |s| str::split(s, ['/', '_', ';']).collect::<Vec<_>>();
    let (g, w) = (split(got), split(want));
    let mut dev = 0.0f64;
    for (g, w) in g.iter().zip(&w) {
        if g == w {
            continue;
        }
        let (a, b) = (g.parse::<f64>().ok()?, w.parse::<f64>().ok()?);
        let close = a.to_bits() == b.to_bits()
            || (trig && (a - b).abs() <= TRIG_TOLERANCE * b.abs().max(1.0));
        dev = dev.max((a - b).abs());
        close.then_some(())?;
    }
    (g.len() == w.len()).then_some(dev)
}

#[derive(Default)]
struct Oracle {
    sets: HashMap<String, Vec<AnimatorStroke>>,
    anims: HashMap<String, Vec<TextAnimator>>,
    rows: Vec<String>,
}

fn oracle() -> Oracle {
    let mut o = Oracle::default();
    for line in ORACLE.lines().filter(|l| !l.starts_with('#')) {
        let (kind, rest) = line.split_once(' ').expect("kind");
        let (id, body) = rest.split_once(' ').unwrap_or((rest, "~"));
        let (id, items) = (id.to_string(), |sep: &'static str| {
            body.split(sep).filter(|b| *b != "~")
        });
        match kind {
            "S" => drop(o.sets.insert(id, items(" ").map(stroke).collect())),
            "A" => drop(o.anims.insert(id, items(" | ").map(animator).collect())),
            _ => o.rows.push(line.to_string()),
        }
    }
    o
}

fn outputs(row: &str) -> (&str, Vec<&str>) {
    let (head, outs) = row.split_once(" =>").expect("row");
    (head, outs.split(' ').filter(|o| !o.is_empty()).collect())
}

#[test]
fn oracle_rows_match_the_baseline() {
    let o = oracle();
    let (mut exact, mut trig, mut max_dev) = (0, 0, 0.0f64);
    for row in &o.rows {
        let (head, outs) = outputs(row);
        let h: Vec<&str> = head.split(' ').collect();
        let strokes = &o.sets[h[2]];
        let input = input(strokes, &o.anims[h[3]], [num(h[4]), num(h[5])]);
        let bases = vec![(h[6] == "b").then_some(BASE); strokes.len()];
        let cs = layer_contributions(&input).expect("contributions");
        let fs = layer_element_motions(&input, &bases).expect("folds");
        assert_eq!(outs.len(), strokes.len(), "{head}");
        for (i, want) in outs.iter().enumerate() {
            let got = encode(&cs[i], &fs[i]);
            let dev = agree(&got, want, h[1] == "t");
            assert!(dev.is_some(), "{head} stroke {i}: {got} != {want}");
            max_dev = max_dev.max(dev.unwrap_or(0.0));
        }
        *if h[1] == "t" { &mut trig } else { &mut exact } += 1;
    }
    assert_eq!(
        (exact, trig),
        (60, 17),
        "oracle hollowed out (max trig deviation {max_dev:e})"
    );
}

#[test]
fn the_oracle_covers_every_skip_pivot_and_colour_rule() {
    let o = oracle();
    assert_eq!((o.sets.len(), o.anims.len()), (6, 14));
    // CONTRIB shapes: `-` null, else present/absent of [motion, anchor, fill, stroke].
    let shape = |c: &str| {
        c.split('/')
            .map(|f| if f == "-" || f == "~" { '-' } else { '+' })
            .collect::<String>()
    };
    let seen: HashSet<String> = o
        .rows
        .iter()
        .flat_map(|r| outputs(r).1)
        .map(|out| shape(out.split(';').next().unwrap_or("")))
        .collect();
    for want in ["-", "+---", "++--", "+-+-", "+--+", "+-++", "++-+", "+++-"] {
        assert!(seen.contains(want), "no oracle contribution shaped {want}");
    }
    // ':' (two contours, charIndex 4) rotates around the whole character.
    let (t, z) = (&o.sets["t"], &o.sets["z"]);
    let colon = unit_pivot_center(t, BasedOn::Chars, 4.0);
    assert_eq!(colon, Some([43.5, 10.5]));
    // The last 'D' segment has no point; it is skipped, not read as the origin.
    let d = stroke_rest_bounds(&t[5].rest_points);
    assert_eq!(d, Some([48.0, 0.0, 59.0, 20.0]));
    assert_eq!(stroke_rest_bounds(&[None, None]), None);
    // `if (v < cur)` keeps the first of two equal zeros: -0 then 0 stays -0.
    let signed = stroke_rest_bounds(&[Some([-0.0, -0.0]), Some([0.0, 0.0])]).expect("box");
    assert!(signed.iter().all(|v| v.to_bits() == (-0.0f64).to_bits()));
    // -0 and 0 are one JS object key, so one unit.
    let zero = unit_pivot_center(z, BasedOn::Chars, -0.0);
    assert_eq!(zero, Some([7.0, 3.0]));
}

/// A valid layer: one stroke `[0, 0]..[4, 2]` at unit 0 and one position animator.
fn layer() -> (Vec<AnimatorStroke>, Vec<TextAnimator>, [f64; 2]) {
    let units = UnitIndices {
        char_index: Some(0.0),
        word_index: None,
        line_index: None,
    };
    let rest_points = vec![Some([0.0, 0.0]), Some([4.0, 2.0])];
    let position = Some([Some(1.0), None]);
    let props = AnimatorProps {
        position,
        ..Default::default()
    };
    let animator = TextAnimator {
        enabled: true,
        props: Some(props),
        selector: Selector::default_selector(),
    };
    (
        vec![AnimatorStroke { units, rest_points }],
        vec![animator],
        [0.0, 24.0],
    )
}

type Contributions = Result<Vec<Option<Contribution>>, TextAnimatorError>;

/// One layer at `t = [frameIdx, fps]`.
fn input<'a>(
    strokes: &'a [AnimatorStroke],
    animators: &'a [TextAnimator],
    t: [f64; 2],
) -> TextAnimatorInput<'a> {
    let (frame_idx, fps) = (t[0], t[1]);
    TextAnimatorInput {
        strokes,
        animators,
        frame_idx,
        fps,
    }
}

fn run(strokes: &[AnimatorStroke], animators: &[TextAnimator], t: [f64; 2]) -> Contributions {
    layer_contributions(&input(strokes, animators, t))
}

/// The first animator's props.
fn p0(a: &mut [TextAnimator]) -> &mut AnimatorProps {
    a[0].props.as_mut().expect("props")
}

fn nan_rgb() -> AnimatorColor {
    AnimatorColor {
        rgb: [NAN; 3],
        alpha: None,
    }
}

type Mutation = fn(&mut Vec<AnimatorStroke>, &mut Vec<TextAnimator>, &mut [f64; 2]);

#[test]
fn every_refusal_comes_before_any_output() {
    use TextAnimatorError::{NonFinite as Nf, TooManyAnimators, TooManyStrokes};

    let cases: [(Mutation, TextAnimatorError); 11] = [
        (|_, _, t| t[0] = NAN, Nf("frameIdx")),
        (|_, _, t| t[1] = f64::INFINITY, Nf("fps")),
        (|_, _, t| *t = [1e308, 1e-10], Nf("timeSec")),
        (|s, _, _| s[0].units.line_index = Some(NAN), Nf("unitIndex")),
        (
            |s, _, _| s[0].rest_points.push(Some([0.0, -1.0 / 0.0])),
            Nf("restPoint"),
        ),
        (|_, a, _| p0(a).rotation = Some(NAN), Nf("rotation")),
        (|_, a, _| p0(a).scale = Some([None, Some(NAN)]), Nf("scale")),
        (|_, a, _| p0(a).opacity = Some(NAN), Nf("opacity")),
        (
            |_, a, _| p0(a).stroke_color = Some(nan_rgb()),
            Nf("strokeColor"),
        ),
        (
            |_, a, _| a.extend([a[0]; MAX_TEXT_ANIMATORS]),
            TooManyAnimators,
        ),
        (
            |s, _, _| s.resize(MAX_ANIMATOR_STROKES + 1, s[0].clone()),
            TooManyStrokes,
        ),
    ];
    for (mutate, want) in cases {
        let (mut s, mut a, mut t) = layer();
        mutate(&mut s, &mut a, &mut t);
        assert_eq!(run(&s, &a, t), Err(want));
    }
}

#[test]
fn a_disabled_animator_and_its_selector_are_still_checked() {
    let (s, mut a, t) = layer();
    a[0].enabled = false;
    assert_eq!(
        run(&s, &a, t),
        Ok(vec![None]),
        "a disabled animator is skipped"
    );
    p0(&mut a).fill_color = Some(AnimatorColor {
        rgb: [0.0; 3],
        alpha: Some(f64::NAN),
    });
    assert_eq!(
        run(&s, &a, t),
        Err(TextAnimatorError::NonFinite("fillColor"))
    );
    p0(&mut a).fill_color = None;
    a[0].selector.wiggle_min = Some(f64::NAN);
    let wiggle_min = SelectorError::NonFinite("wiggleMin");
    assert_eq!(run(&s, &a, t), Err(TextAnimatorError::Selector(wiggle_min)));
    // Two maximal positions overflow only in the sum: still refused, not returned.
    let (s, mut a, t) = layer();
    p0(&mut a).position = Some([Some(f64::MAX), None]);
    a.push(a[0]);
    assert_eq!(run(&s, &a, t), Err(TextAnimatorError::NonFiniteResult));
}

#[test]
fn the_unit_count_is_bounded_like_the_selector() {
    let (mut s, a, t) = layer();
    s[0].units.char_index = Some(65_536.0);
    assert_eq!(run(&s, &a, t), Err(TextAnimatorError::TooManyUnits));
    s[0].units.char_index = Some(65_535.0);
    assert!(run(&s, &a, t).is_ok(), "65 536 units are served");
}

#[test]
fn the_fold_returns_the_base_without_a_contribution_and_clamps_opacity() {
    assert_eq!(fold_element_motion(None, None), Ok(None));
    let f = fold_element_motion(Some(BASE), None).unwrap().unwrap();
    assert_eq!((f.motion, f.fill, f.stroke), (BASE, None, None));
    let bad = ElementMotion {
        op: f64::NAN,
        ..BASE
    };
    assert_eq!(
        fold_element_motion(Some(bad), None),
        Err(TextAnimatorError::NonFinite("baseMotion"))
    );
    let (s, mut a, _) = layer();
    p0(&mut a).opacity = Some(400.0);
    let c = run(&s, &a, [3.0, 0.0]).unwrap();
    let f = fold_element_motion(None, c[0].as_ref()).unwrap().unwrap();
    assert_eq!(f.motion.op, 1.0, "opacity is clamped to 1");
    assert_eq!(
        c,
        run(&s, &a, [3.0, 0.0]).unwrap(),
        "same inputs, same bits"
    );
    let mismatch = layer_element_motions(&input(&s, &a, [0.0, 24.0]), &[]);
    assert_eq!(mismatch, Err(TextAnimatorError::BaseCountMismatch));
}

