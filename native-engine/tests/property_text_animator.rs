//! Oracle and control tests for the text animator contribution kernel (D28-K1).
//!
//! `ORACLE` below was produced by a Node generator kept outside the repo
//! (`gen.js`, sha256
//! ec74ce9b07d201420b0af58237ec25cbe388cec3c1a51b4e46e24e07a2ef55e3) that cuts
//! `taSelectorAt`, `_exprFps`, `taUnitCount`, `_taStrokeRestBounds`, `taUnitPivotCenter`,
//! `textAnimatorContribution` and `elementMotionAt` VERBATIM from
//! `src/js/motion.js` (sha256
//! d38fcb0502e395045543a571531b15a1185c04106e04db165bd2949ed863d7ec) and runs
//! them against the unmodified `src/js/text-selector.js` (sha256
//! 47aa4045e031eeb32b2d4505e3ae9d06ada684fc497de439976eb25838430b11), both at
//! ca931b5a, with shims only for `state`, `getEffectiveStrokes` and
//! `computeMotionMat` (the base holder is the base motion itself).
//!
//! Numbers are JS `String(n)` with `-0` kept; `-` is null / undefined.
//! * `S id STROKE..` (`~` none): `c,w,l=PTS`, PTS `x_y` points joined by `;`,
//!   `!` a segment without a point, `~` no segments.
//! * `A id ANIM | ANIM..`: `en(y|n) SEL16 PROPS`; SEL16 is `selectorType start
//!   end offset units basedOn shape amount easeHigh easeLow smooth wiggleMin
//!   wiggleMax wigglesPerSec correlation seed` (strings as spelled, an absent
//!   one as its default; `-` in a `||` field reads 0); PROPS `~` null, `.`
//!   empty, else `pos=a_b,rot=r,scl=a_b,op=o,fc=r_g_b_a,sc=r_g_b_a`. A `null`
//!   animator entry (a JS-side skip) is omitted from the native list.
//! * `R trig set anims frame fps base(b|~) => OUT..`, one OUT per stroke:
//!   `CONTRIB;FOLD`, CONTRIB `~` or `dx_dy_rot_sx_sy_op/ANCHOR/FILL/STROKE`, FOLD
//!   `~` or `dx_dy_rot_sx_sy_op_ax_ay/FILL/STROKE`, a pull `t0_t1_t2_t3_blend`.
//!
//! `x` rows compare bit for bit. `t` rows (Wiggly, SMOOTH) reach `sin`/`cos`
//! through the selector and are held within [`TRIG_TOLERANCE`] (relative),
//! the selector's own V8 bound policy.

