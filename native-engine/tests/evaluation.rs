const PROJECT: &[u8] = include_bytes!("fixtures/opacity-v2/project.json");
const LAYER: &str = "r08_curve_layer";

fn application(bytes: &[u8]) -> NativeOpacityApplication {
    NativeOpacityApplication::new("native-evaluation-a", decode_project(bytes).unwrap()).unwrap()
}

fn project_value() -> Value {
    serde_json::from_slice(PROJECT).unwrap()
}

fn unchecked_snapshot(value: &Value) -> DocumentSnapshot {
    let document: OpacityDocument = serde_json::from_value(value.clone()).unwrap();
    NativeOpacityApplication::new("native-evaluation-unchecked", document)
        .unwrap()
        .acquire_snapshot(0)
        .unwrap()
}

fn value_at(snapshot: &DocumentSnapshot, frame: u32) -> crate::evaluation::OpacityEvaluation {
    evaluate(snapshot, SUPPORTED_CONTEXT_ID, frame).expect("admitted frame must evaluate")
}

#[test]
fn fixed_curve_evaluates_from_immutable_snapshot_with_stable_identity() {
    let app = application(PROJECT);
    let snapshot = app.acquire_snapshot(0).unwrap();
    let before = encode_project(snapshot.document()).unwrap();
    // The interior samples are frozen from src/js/animation/curve.js, not
    // generated by this candidate. They distinguish the cubic evaluator from
    // a linear interpolation that would also pass 20/50/80.
    let expected = [
        (0, 20.0),
        (2, 23.089_347_448_028_04),
        (5, 29.36),
        (10, 50.0),
        (15, 70.64),
        (18, 76.910_652_551_971_96),
        (20, 80.0),
    ];

    for (frame, opacity) in expected {
        let first = value_at(&snapshot, frame);
        let repeated = value_at(&snapshot, frame);
        assert_eq!(first, repeated, "identical inputs must be deterministic");
        assert_eq!(first.document_snapshot_id(), snapshot.id());
        assert_eq!(first.document_id(), snapshot.document_id());
        assert_eq!(first.content_revision(), 0);
        assert_eq!(first.context_id(), "scene-root");
        assert_eq!(first.frame(), frame);
        assert_eq!(first.layers().len(), 1);
        assert_eq!(first.layers()[0].layer_uid(), LAYER);
        assert!(
            (first.layers()[0].value() - opacity).abs() < 1e-10,
            "frame {frame}: expected {opacity}, got {}",
            first.layers()[0].value()
        );
    }

    assert_eq!(encode_project(snapshot.document()).unwrap(), before);
    let reloaded = application(&before).acquire_snapshot(0).unwrap();
    for (frame, opacity) in expected {
        close(value_at(&reloaded, frame).layers()[0].value(), opacity);
    }
    assert_eq!(snapshot.id(), app.acquire_snapshot(0).unwrap().id());
    assert_eq!(app.content_revision(), 0);
}

#[test]
fn held_old_snapshot_does_not_reread_a_later_commit() {
    let mut static_project = project_value();
    static_project["layers"][0]
        .as_object_mut()
        .unwrap()
        .remove("motion");
    let bytes = serde_json::to_vec(&static_project).unwrap();
    let mut app = application(&bytes);
    let old = app.acquire_snapshot(0).unwrap();
    let old_bytes = encode_project(old.document()).unwrap();
    assert_eq!(value_at(&old, 10).layers()[0].value(), 25.0);

    let command = OpacityRequest::command(
        "evaluation-set-40",
        app.instance_id(),
        app.document_id(),
        app.content_revision(),
        json!({
            "command": "layer.opacity.set",
            "stableTarget": { "layerUid": LAYER },
            "value": 40
        }),
    );
    let response = app.handle(command);
    assert!(response.is_ok());
    assert_eq!(response.content_revision(), 1);
    let current = app.acquire_snapshot(1).unwrap();

    let old_again = value_at(&old, 10);
    let current_value = value_at(&current, 10);
    assert_eq!(old_again.layers()[0].value(), 25.0);
    assert_eq!(current_value.layers()[0].value(), 40.0);
    assert_eq!(old_again.content_revision(), 0);
    assert_eq!(current_value.content_revision(), 1);
    assert_ne!(
        old_again.document_snapshot_id(),
        current_value.document_snapshot_id()
    );
    assert_eq!(old_again.document_id(), current_value.document_id());
    assert_eq!(encode_project(old.document()).unwrap(), old_bytes);
    assert_eq!(app.content_revision(), 1);
}

#[test]
fn context_and_frame_are_explicit_and_never_silently_substituted() {
    let app = application(PROJECT);
    let snapshot = app.acquire_snapshot(0).unwrap();
    for context in ["", "component-context"] {
        let error = evaluate(&snapshot, context, 10).unwrap_err();
        assert_eq!(error.kind(), EvaluationErrorKind::Unsupported);
        assert!(error.message().contains("scene-root"));
    }
    let error = evaluate(&snapshot, SUPPORTED_CONTEXT_ID, 21).unwrap_err();
    assert_eq!(error.kind(), EvaluationErrorKind::OutOfRange);
    assert!(error.message().contains("totalFrames 21"));
    assert_eq!(app.content_revision(), 0);
}

#[test]
fn unsupported_or_malformed_interpolation_is_rejected_before_evaluation() {
    let mut position = project_value();
    position["layers"][0]["motion"]["position"] = json!({ "keys": [] });
    assert_eq!(
        decode_project(&serde_json::to_vec(&position).unwrap())
            .unwrap_err()
            .kind(),
        CodecErrorKind::Unsupported
    );

    let mut hold = project_value();
    hold["layers"][0]["motion"]["opacity"]["keys"][0]["hold"] = json!(true);
    assert_eq!(
        decode_project(&serde_json::to_vec(&hold).unwrap())
            .unwrap_err()
            .kind(),
        CodecErrorKind::Unsupported
    );

    let mut changed_curve = project_value();
    changed_curve["layers"][0]["motion"]["opacity"]["keys"][0]["curvePoints"][1]["y"] = json!(0.25);
    assert_eq!(
        decode_project(&serde_json::to_vec(&changed_curve).unwrap())
            .unwrap_err()
            .kind(),
        CodecErrorKind::Unsupported
    );
    assert_eq!(
        evaluate(
            &unchecked_snapshot(&changed_curve),
            SUPPORTED_CONTEXT_ID,
            10
        )
        .unwrap_err()
        .kind(),
        EvaluationErrorKind::Unsupported
    );

    let mut nonzero_handle = project_value();
    nonzero_handle["layers"][0]["motion"]["opacity"]["keys"][0]["hOut"] = json!([1, 0]);
    assert_eq!(
        decode_project(&serde_json::to_vec(&nonzero_handle).unwrap())
            .unwrap_err()
            .kind(),
        CodecErrorKind::Unsupported
    );
    assert_eq!(
        evaluate(
            &unchecked_snapshot(&nonzero_handle),
            SUPPORTED_CONTEXT_ID,
            10
        )
        .unwrap_err()
        .kind(),
        EvaluationErrorKind::Unsupported
    );

    let mut short_curve = project_value();
    short_curve["layers"][0]["motion"]["opacity"]["keys"][0]["curvePoints"]
        .as_array_mut()
        .unwrap()
        .pop();
    assert_eq!(
        decode_project(&serde_json::to_vec(&short_curve).unwrap())
            .unwrap_err()
            .kind(),
        CodecErrorKind::Invalid
    );
    assert_eq!(
        evaluate(&unchecked_snapshot(&short_curve), SUPPORTED_CONTEXT_ID, 10)
            .unwrap_err()
            .kind(),
        EvaluationErrorKind::Invalid
    );

    let mut unordered_keys = project_value();
    unordered_keys["layers"][0]["motion"]["opacity"]["keys"][1]["frame"] = json!(0);
    assert_eq!(
        decode_project(&serde_json::to_vec(&unordered_keys).unwrap())
            .unwrap_err()
            .kind(),
        CodecErrorKind::Invalid
    );
    assert_eq!(
        evaluate(
            &unchecked_snapshot(&unordered_keys),
            SUPPORTED_CONTEXT_ID,
            10
        )
        .unwrap_err()
        .kind(),
        EvaluationErrorKind::Invalid
    );

    let mut out_of_range_static = project_value();
    out_of_range_static["layers"][0]
        .as_object_mut()
        .unwrap()
        .remove("motion");
    out_of_range_static["layers"][0]["motionStatic"]["opacity"][0] = json!(101);
    assert_eq!(
        evaluate(
            &unchecked_snapshot(&out_of_range_static),
            SUPPORTED_CONTEXT_ID,
            10
        )
        .unwrap_err()
        .kind(),
        EvaluationErrorKind::Invalid
    );
}

