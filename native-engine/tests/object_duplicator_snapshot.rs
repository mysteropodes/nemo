//! Literal baseline values through the real native codec, snapshot and new port.
use super::{MotionPort, SnapshotMotion, Unavailable};
use crate::evaluation::object_component_kernels::duplicator_placement_modes::JsNumber;
use crate::object_codec::{decode_project, encode_project};
use crate::revision::ObjectSnapshot;
use serde_json::{json, Value};

fn source(properties: Value) -> Value {
    json!({"format":"nemo.native-object-document","formatVersion":1,"totalFrames":8,
        "layers":[{"layerUid":"L0"}],"objects":[],
        "propertyHolders":[{"target":{"contextId":"scene-root","layerUid":"L0"},
            "properties":properties}]})
}
fn snapshot(properties: Value) -> ObjectSnapshot {
    ObjectSnapshot::new(
        "duplicator-native-inputs",
        decode_project(source(properties).to_string().as_bytes()).unwrap(),
    )
    .unwrap()
}
fn values(values: &[f64]) -> Option<Vec<JsNumber>> {
    Some(values.iter().copied().map(JsNumber::Value).collect())
}

#[test]
fn original_effector_catalog_defaults_dimensions_and_units_reach_the_real_port() {
    // effector-layer.js propKeysFor/resolveEffector, not generated by this port.
    let cases: &[(&str, &[f64], &str)] = &[
        ("effRadius", &[200.], "px"),
        ("effStrength", &[100.], "%"),
        ("effAngle", &[0.], "°"),
        ("effOffPosition", &[0., 0.], "px"),
        ("effOffRotation", &[0.], "°"),
        ("effOffScale", &[0., 0.], "%"),
        ("effOffOpacity", &[0.], "%"),
        ("effOffPositionZ", &[0.], "px"),
        ("effOffRotationX", &[0.], "°"),
        ("effOffRotationY", &[0.], "°"),
    ];
    let snap = snapshot(json!([]));
    let port = SnapshotMotion::new(&snap, "scene-root", 0.);
    let holder = &snap.document().property_holders().unwrap()[0];
    for &(key, expected, unit) in cases {
        let metadata = holder.metadata_in_document(snap.document(), key).unwrap();
        assert_eq!(metadata.dimension(), expected.len(), "{key}");
        assert_eq!(metadata.unit(), unit, "{key}");
        assert_eq!(port.value("L0", key), Ok(values(expected)), "{key}");
    }
}

#[test]
fn actual_stored_duplicator_and_effector_tracks_sample_fractional_time_without_mutation() {
    let snap = snapshot(json!([
        {"property":"dupOffsetPos","track":{"keys":[
            {"frame":0,"v":[0,10],"curvePoints":[]}, {"frame":4,"v":[40,50]}]}},
        {"property":"effRadius","track":{"keys":[
            {"frame":0,"v":[100],"curvePoints":[]}, {"frame":4,"v":[500]}]}},
        {"property":"effOffScale","static":[-25,75]}
    ]));
    let before = encode_project(snap.document()).unwrap();
    let later = SnapshotMotion::new(&snap, "scene-root", 2.5);
    assert_eq!(later.value("L0", "dupOffsetPos"), Ok(values(&[25., 35.])));
    assert_eq!(later.value("L0", "effRadius"), Ok(values(&[350.])));
    assert_eq!(later.value("L0", "effOffScale"), Ok(values(&[-25., 75.])));
    let initial = SnapshotMotion::new(&snap, "scene-root", 0.);
    assert_eq!(initial.value("L0", "dupOffsetPos"), Ok(values(&[0., 10.])));
    assert_eq!(encode_project(snap.document()).unwrap(), before);
}

#[test]
fn enabled_expressions_are_not_silently_replaced_by_static_or_catalog_values() {
    let snap = snapshot(json!([
        {"property":"effRadius","static":[200],"expression":{"enabled":true,"code":"400"}},
        {"property":"position","static":[10,20],"expression":{"enabled":true,"code":"[30,40]"}}
    ]));
    let port = SnapshotMotion::new(&snap, "scene-root", 2.);
    assert_eq!(
        port.value("L0", "effRadius"),
        Err(Unavailable::Property("effRadius"))
    );
    assert_eq!(
        port.value("L0", "position"),
        Err(Unavailable::Property("position"))
    );
    assert_eq!(port.motion_delta("L0"), Err(Unavailable::LayerMotion));
}

