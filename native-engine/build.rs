//! Build-time registration for the native engine (CS2/#2345), in the style of nemo-mcp/build.rs.
//!
//! * `tests/*.rs` files declare their Cargo-feature harness with header lines
//!   `//! nemo-test-harness: <feature> => <module_name>`; this writes `test_modules.rs`.
//! * `src/object_command_families/*.rs` (except `mod.rs`) each define `FAMILY`; this writes
//!   `command_families.rs` with their `mod` declarations and `FAMILIES`.
//!   An optional `//! nemo-command-feature: <feature>` header gates both on that Cargo feature.
//! * The `command.document.object.*` operations declared in
//!   `engineering/application/capabilities-v2/*.json` are embedded for the ownership test.
//! * Orphan check: a tests/*.rs file with no harness header and no `#[path]` include from src or
//!   tests fails the build, so a test file can never be silently unrun. Chosen in build.rs rather
//!   than a node gate because it fires on every `cargo` invocation, including the documented
//!   per-target commands, and needs no extra CI lane.
use std::{
    collections::BTreeSet,
    env, fs,
    path::{Path, PathBuf},
};

const HARNESS_PREFIX: &str = "//! nemo-test-harness:";

fn rust_files(dir: &Path) -> Vec<PathBuf> {
    let mut files: Vec<_> = fs::read_dir(dir)
        .unwrap_or_else(|error| panic!("read {}: {error}", dir.display()))
        .map(|entry| entry.expect("readable directory entry").path())
        .filter(|path| path.extension().is_some_and(|ext| ext == "rs"))
        .collect();
    files.sort();
    files
}

fn walk(dir: &Path, out: &mut Vec<PathBuf>) {
    for entry in fs::read_dir(dir).unwrap_or_else(|e| panic!("read {}: {e}", dir.display())) {
        let path = entry.expect("readable entry").path();
        if path.is_dir() {
            walk(&path, out);
        } else if path.extension().is_some_and(|ext| ext == "rs") {
            out.push(path);
        }
    }
}

fn out_file(name: &str, text: &str) {
    let target = Path::new(&env::var("OUT_DIR").expect("cargo sets OUT_DIR")).join(name);
    fs::write(&target, text).unwrap_or_else(|error| panic!("write {}: {error}", target.display()));
}

/// Harness header lines of a test file, as (feature, module) pairs.
fn harness_headers(text: &str) -> Vec<(String, String)> {
    text.lines()
        .take_while(|line| line.starts_with("//!"))
        .filter_map(|line| line.strip_prefix(HARNESS_PREFIX))
        .map(|spec| {
            let (feature, module) = spec
                .split_once("=>")
                .unwrap_or_else(|| panic!("malformed nemo-test-harness header: {spec:?}"));
            let (feature, module) = (feature.trim(), module.trim());
            assert!(
                feature.starts_with("test-") && !module.is_empty(),
                "nemo-test-harness header needs `test-<name> => <module>`: {spec:?}"
            );
            (feature.to_owned(), module.to_owned())
        })
        .collect()
}

fn test_modules(manifest: &Path) {
    let tests = manifest.join("tests");
    println!("cargo:rerun-if-changed={}", tests.display());
    let mut all_sources = Vec::new();
    walk(&manifest.join("src"), &mut all_sources);
    all_sources.extend(rust_files(&tests));
    let source_text: Vec<String> = all_sources
        .iter()
        .map(|path| fs::read_to_string(path).unwrap_or_default())
        .collect();
    let mut out = String::from("// Generated by build.rs from `nemo-test-harness` headers.\n");
    let mut seen = BTreeSet::new();
    for file in rust_files(&tests) {
        println!("cargo:rerun-if-changed={}", file.display());
        let text = fs::read_to_string(&file).expect("readable test file");
        let name = file
            .file_name()
            .expect("file name")
            .to_string_lossy()
            .into_owned();
        let headers = harness_headers(&text);
        for (feature, module) in &headers {
            assert!(
                seen.insert(module.clone()),
                "duplicate nemo-test-harness module name {module:?} ({name})"
            );
            out.push_str(&format!(
                "#[cfg(feature = {feature:?})]\n#[path = {:?}]\nmod {module};\n",
                file.canonicalize()
                    .expect("canonical test path")
                    .display()
                    .to_string()
            ));
        }
        if headers.is_empty() {
            // `#[path = "../tests/x.rs"]` from src, or `#[path = "x.rs"]` from a sibling test file.
            let needles = [format!("/{name}\""), format!("\"{name}\"")];
            let included = all_sources.iter().zip(&source_text).any(|(path, text)| {
                *path != file && needles.iter().any(|needle| text.contains(needle))
            });
            assert!(
                included,
                "orphan test file tests/{name}: it has no `//! nemo-test-harness: <feature> => <module>` \
                 header and no `#[path = \"../tests/{name}\"]` include from native-engine/src or tests, \
                 so no test target would ever run it"
            );
        }
    }
    out_file("test_modules.rs", &out);
}

fn command_families(manifest: &Path) {
    let dir = manifest.join("src/object_command_families");
    let cargo = fs::read_to_string(manifest.join("Cargo.toml")).expect("readable Cargo manifest");
    let features: BTreeSet<_> = cargo
        .split("[features]")
        .nth(1)
        .expect("Cargo features table")
        .lines()
        .take_while(|line| !line.starts_with('['))
        .filter_map(|line| line.split_once('=').map(|(name, _)| name.trim()))
        .collect();
    println!("cargo:rerun-if-changed={}", dir.display());
    let mut out = String::from("// Generated by build.rs from src/object_command_families/*.rs.\n");
    let mut names = Vec::new();
    for file in rust_files(&dir) {
        if file.file_name().is_some_and(|name| name == "mod.rs") {
            continue;
        }
        println!("cargo:rerun-if-changed={}", file.display());
        let module = file
            .file_stem()
            .expect("stem")
            .to_string_lossy()
            .into_owned();
        let text = fs::read_to_string(&file).expect("readable command family");
        let gates: Vec<_> = text
            .lines()
            .take_while(|line| line.starts_with("//!"))
            .filter_map(|line| line.strip_prefix("//! nemo-command-feature:"))
            .map(str::trim)
            .collect();
        assert!(gates.len() <= 1, "one command feature per family: {module}");
        let cfg = gates
            .first()
            .map(|feature| {
                assert!(
                    features.contains(feature),
                    "unknown Cargo command feature {feature:?}: {module}"
                );
                format!("#[cfg(feature = {feature:?})]\n")
            })
            .unwrap_or_default();
        out.push_str(&format!(
            "{cfg}#[path = {:?}]\npub(crate) mod {module};\n",
            file.canonicalize()
                .expect("canonical family path")
                .display()
                .to_string()
        ));
        names.push((module, cfg));
    }
    out.push_str("pub(crate) const FAMILIES: &[&CommandFamily] = &[\n");
    for (module, cfg) in &names {
        out.push_str(&format!("    {cfg}&{module}::FAMILY,\n"));
    }
    out.push_str("];\n");
    out_file("command_families.rs", &out);
}

/// `command.document.object.*` entries of every `"operations": [...]` array in the v2 capability files.
fn declared_object_operations(manifest: &Path) {
    let dir = manifest.join("../engineering/application/capabilities-v2");
    println!("cargo:rerun-if-changed={}", dir.display());
    let mut files: Vec<_> = fs::read_dir(&dir)
        .unwrap_or_else(|error| panic!("read {}: {error}", dir.display()))
        .map(|entry| entry.expect("readable entry").path())
        .filter(|path| path.extension().is_some_and(|ext| ext == "json"))
        .collect();
    files.sort();
    let mut operations = BTreeSet::new();
    for file in &files {
        println!("cargo:rerun-if-changed={}", file.display());
        let text = fs::read_to_string(file).expect("readable capability file");
        let Some(start) = text.find("\"operations\"") else {
            continue;
        };
        let rest = &text[start..];
        let (Some(open), Some(close)) = (rest.find('['), rest.find(']')) else {
            continue;
        };
        for item in rest[open + 1..close].split(',') {
            let item = item.trim().trim_matches('"');
            if item.starts_with("command.document.object.") {
                operations.insert(item.to_owned());
            }
        }
    }
    assert!(
        !operations.is_empty(),
        "no declared object operations found"
    );
    let mut out = String::from("pub(crate) const DECLARED_OBJECT_OPERATIONS: &[&str] = &[\n");
    for operation in &operations {
        out.push_str(&format!("    {operation:?},\n"));
    }
    out.push_str("];\n");
    out_file("declared_object_operations.rs", &out);
}

fn main() {
    let manifest =
        PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("cargo sets CARGO_MANIFEST_DIR"));
    println!("cargo:rerun-if-changed=build.rs");
    test_modules(&manifest);
    command_families(&manifest);
    declared_object_operations(&manifest);
}
