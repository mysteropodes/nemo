//! G44 (#2357): the After Effects camera script (`.jsx`) as a pure kernel over the pinned stored camera state.
//! Port of baseline `src/js/ae-camera-export.js` @1065e9d8: the same keyframe times (frame / fps), the same
//! Point of Interest / Position / Z Rotation values and the same ExtendScript text. Linear interpolation only, as in
//! the baseline (AE re-eases natively). The job route that writes the file rides the EXPORT-A lane.
use crate::revision::ObjectSnapshot;
use serde::Deserialize;

/// The baseline refusal text when the camera layer is off or there are no keys.
pub(crate) const NO_ACTIVE_CAMERA: &str = "Aucun calque caméra actif — rien à exporter.";

/// One stored camera key: only what the script writes (handles and ease are not exported).
#[derive(Debug, Clone, PartialEq, Deserialize)]
pub(crate) struct AeCameraKey {
    pub(crate) frame: f64,
    pub(crate) x: f64,
    pub(crate) y: f64,
    pub(crate) w: f64,
    #[serde(default)]
    pub(crate) rot: Option<f64>,
}

#[derive(Debug, Clone, PartialEq)]
pub(crate) struct AeCameraScript {
    pub(crate) script: String,
    pub(crate) key_count: usize,
}
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) enum AeCameraExportError {
    /// The project carries no camera state at all (neither keys nor layer flag).
    Unavailable,
    /// Camera layer off or no keys: the baseline message.
    Refused(&'static str),
    /// A time or coordinate is not a finite number.
    NotFinite,
}

/// JavaScript `String(x)` for a finite number (exponent forms included; -0 is `0`).
pub(crate) fn js_number(x: f64) -> String {
    if x == 0.0 {
        return "0".to_owned();
    }
    let sci = format!("{:e}", x.abs());
    let (mantissa, exp) = sci.split_once('e').unwrap_or((sci.as_str(), "0"));
    let digits: String = mantissa.chars().filter(|c| *c != '.').collect();
    let k = digits.len() as i32;
    let n = exp.parse::<i32>().unwrap_or(0) + 1;
    let sign = if x < 0.0 { "-" } else { "" };
    let body = if k <= n && n <= 21 {
        format!("{digits}{}", "0".repeat((n - k) as usize))
    } else if 0 < n && n <= 21 {
        format!("{}.{}", &digits[..n as usize], &digits[n as usize..])
    } else if -6 < n && n <= 0 {
        format!("0.{}{digits}", "0".repeat((-n) as usize))
    } else {
        let e = n - 1;
        let tail = format!("e{}{}", if e < 0 { "-" } else { "+" }, e.abs());
        if k == 1 {
            format!("{digits}{tail}")
        } else {
            format!("{}.{}{tail}", &digits[..1], &digits[1..])
        }
    };
    format!("{sign}{body}")
}

fn triple(x: f64, y: f64, z: f64) -> String {
    format!("[{},{},{}]", js_number(x), js_number(y), js_number(z))
}
fn list(items: &[String]) -> String {
    format!("[{}]", items.join(","))
}

/// The script for the stored keys at the project's fps and canvas width (the fixed AE Zoom).
pub(crate) fn build_ae_camera_script(
    keys: Option<&[AeCameraKey]>,
    layer_on: Option<bool>,
    fps: f64,
    canvas_w: u32,
) -> Result<AeCameraScript, AeCameraExportError> {
    if keys.is_none() && layer_on.is_none() {
        return Err(AeCameraExportError::Unavailable);
    }
    let keys = keys.unwrap_or(&[]);
    if layer_on != Some(true) || keys.is_empty() {
        return Err(AeCameraExportError::Refused(NO_ACTIVE_CAMERA));
    }
    let mut sorted: Vec<&AeCameraKey> = keys.iter().collect();
    sorted.sort_by(|a, b| a.frame.total_cmp(&b.frame));
    let (mut times, mut poi, mut pos, mut rot) = (vec![], vec![], vec![], vec![]);
    for key in sorted {
        let time = key.frame / fps;
        if !time.is_finite() {
            return Err(AeCameraExportError::NotFinite);
        }
        times.push(js_number(time));
        poi.push(triple(key.x, key.y, 0.0));
        pos.push(triple(key.x, key.y, -key.w));
        rot.push(js_number(key.rot.unwrap_or(0.0)));
    }
    let (times, poi, pos, rot) = (list(&times), list(&poi), list(&pos), list(&rot));
    let lines = [
        "// Generated by Nemo — recreates the camera move as a real, editable".to_owned(),
        "// After Effects camera. Run from After Effects: File > Scripts > Run Script File…".to_owned(),
        "// (with a composition open/selected) — or drop this file into the".to_owned(),
        "// ScriptUI Panels folder to run it from the Window menu instead.".to_owned(),
        "(function(){".to_owned(),
        "  var comp = app.project.activeItem;".to_owned(),
        "  if (!(comp && comp instanceof CompItem)) {".to_owned(),
        "    alert(\"Ouvre ou sélectionne une composition dans After Effects, puis relance ce script.\");".to_owned(),
        "    return;".to_owned(),
        "  }".to_owned(),
        "  app.beginUndoGroup(\"Import caméra Nemo\");".to_owned(),
        "  try {".to_owned(),
        "    var cam = comp.layers.addCamera(\"Nemo Camera\", [comp.width/2, comp.height/2]);".to_owned(),
        format!("    cam.property(\"Camera Options\").property(\"Zoom\").setValue({canvas_w});"),
        "    var poi = cam.property(\"Transform\").property(\"Point of Interest\");".to_owned(),
        "    var pos = cam.property(\"Transform\").property(\"Position\");".to_owned(),
        "    var rotZ = cam.property(\"Transform\").property(\"Z Rotation\");".to_owned(),
        format!("    var times = {times};"),
        format!("    poi.setValuesAtTimes(times, {poi});"),
        format!("    pos.setValuesAtTimes(times, {pos});"),
        format!("    rotZ.setValuesAtTimes(times, {rot});"),
        "    for (var i = 1; i <= poi.numKeys; i++) poi.setInterpolationTypeAtKey(i, KeyframeInterpolationType.LINEAR, KeyframeInterpolationType.LINEAR);".to_owned(),
        "    for (var i = 1; i <= pos.numKeys; i++) pos.setInterpolationTypeAtKey(i, KeyframeInterpolationType.LINEAR, KeyframeInterpolationType.LINEAR);".to_owned(),
        "    for (var i = 1; i <= rotZ.numKeys; i++) rotZ.setInterpolationTypeAtKey(i, KeyframeInterpolationType.LINEAR, KeyframeInterpolationType.LINEAR);".to_owned(),
        "    alert(\"Caméra Nemo importée : \" + times.length + \" image(s)-clé.\");".to_owned(),
        "  } catch (e) {".to_owned(),
        "    alert(\"Échec de l'import caméra : \" + e.toString());".to_owned(),
        "  }".to_owned(),
        "  app.endUndoGroup();".to_owned(),
        "})();".to_owned(),
    ];
    Ok(AeCameraScript {
        script: lines.join("\n"),
        key_count: keys.len(),
    })
}

/// The same script over a pinned snapshot's stored camera, canvas width and fps.
pub(crate) fn build_ae_camera_script_for(
    snapshot: &ObjectSnapshot,
) -> Result<AeCameraScript, AeCameraExportError> {
    let project = snapshot
        .project()
        .ok_or(AeCameraExportError::Unavailable)?
        .project();
    let keys: Option<Vec<AeCameraKey>> = project.camera_keys().map(|stored| {
        stored
            .iter()
            .map(|k| AeCameraKey {
                frame: k.frame,
                x: k.x,
                y: k.y,
                w: k.w,
                rot: k.rot.value().copied(),
            })
            .collect()
    });
    build_ae_camera_script(
        keys.as_deref(),
        project.camera_layer_on(),
        project.fps(),
        project.canvas_dimensions().0,
    )
}

