use std::{env, fs, path::Path, process::Command};

fn git(args: &[&str]) -> Option<String> {
    let output = Command::new("git").args(args).output().ok()?;
    output
        .status
        .success()
        .then(|| String::from_utf8_lossy(&output.stdout).trim().to_owned())
}

/// Native v2 declarations are discovered from their directory (CS1/#2341), so a
/// feature registers by adding its own descriptor file instead of editing a
/// shared Rust list. Sorted by file name for a deterministic catalog order.
fn native_capability_sources() {
    let manifest = env::var("CARGO_MANIFEST_DIR").expect("cargo sets CARGO_MANIFEST_DIR");
    let dir = Path::new(&manifest).join("../engineering/application/capabilities-v2");
    println!("cargo:rerun-if-changed={}", dir.display());
    let mut files: Vec<_> = fs::read_dir(&dir)
        .unwrap_or_else(|error| panic!("read {}: {error}", dir.display()))
        .map(|entry| entry.expect("readable capabilities-v2 entry").path())
        .filter(|path| path.extension().is_some_and(|ext| ext == "json"))
        .collect();
    files.sort();
    assert!(
        !files.is_empty(),
        "no native capability declarations in {}",
        dir.display()
    );
    let mut out = String::from(
        "/// Generated by build.rs from engineering/application/capabilities-v2/*.json.\n\
         pub const NATIVE_CAPABILITY_SOURCES: &[&str] = &[\n",
    );
    let mut names = String::from("pub const NATIVE_CAPABILITY_FILES: &[&str] = &[\n");
    for path in &files {
        let path = path.canonicalize().expect("canonical descriptor path");
        println!("cargo:rerun-if-changed={}", path.display());
        out.push_str(&format!(
            "    include_str!({:?}),\n",
            path.display().to_string()
        ));
        let name = path
            .file_name()
            .expect("descriptor file name")
            .to_string_lossy();
        names.push_str(&format!("    {name:?},\n"));
    }
    out.push_str("];\n");
    names.push_str("];\n");
    out.push_str("/// File names, in the same order as `NATIVE_CAPABILITY_SOURCES`.\n");
    out.push_str(&names);
    let target = Path::new(&env::var("OUT_DIR").expect("cargo sets OUT_DIR"))
        .join("native_capability_sources.rs");
    fs::write(&target, out).unwrap_or_else(|error| panic!("write {}: {error}", target.display()));
}

fn main() {
    native_capability_sources();
    let sha = git(&["rev-parse", "HEAD"]).unwrap_or_else(|| "source-unknown".into());
    let dirty = git(&["status", "--porcelain", "--untracked-files=no"])
        .map(|status| !status.is_empty())
        .unwrap_or(true);
    println!(
        "cargo:rustc-env=NEMO_MCP_SOURCE_ID={sha}{}",
        if dirty { "-dirty" } else { "" }
    );
    for path in [
        "src",
        "Cargo.toml",
        "Cargo.lock",
        "../src",
        "../src-tauri/src",
    ] {
        println!("cargo:rerun-if-changed={path}");
    }
    if let Some(path) = git(&["rev-parse", "--git-path", "HEAD"]) {
        println!("cargo:rerun-if-changed={path}");
    }
    if let Some(reference) = git(&["symbolic-ref", "-q", "HEAD"]) {
        if let Some(path) = git(&["rev-parse", "--git-path", &reference]) {
            println!("cargo:rerun-if-changed={path}");
        }
    }
}
