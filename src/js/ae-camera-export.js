// ---- Export Nemo's camera to a real After Effects Camera layer, via a
// generated ExtendScript (.jsx) the user runs from AE itself
// (File > Scripts > Run Script File…) ----
//
// Not baked into rendered frames (that's what the PNG/MP4/etc exporters
// already do, camera included, via SMCamera.applyToExportLayer) — this
// produces an actual, still-editable AE Camera layer with keyframed
// Position/Point of Interest/Zoom/Rotation, so the camera move can be
// retimed, eased, or combined with other AE camera work after import.
//
// AE camera math: a 2-node camera (Position + Point of Interest, no
// separate Orientation) looking straight down its own view axis at the
// comp's Z=0 plane reproduces Nemo's 2D pan/zoom exactly if:
//   - Point of Interest = (cam.x, cam.y, 0)  — what it's centered on
//   - Position          = (cam.x, cam.y, -cam.w * Zoom / compWidth)
//   - Zoom is fixed (kept CONSTANT, not animated) at any reference value;
//     the visible width at distance d from a camera with a given Zoom is
//     d * compWidth / Zoom (standard AE perspective relationship), so
//     fixing Zoom = compWidth makes that formula collapse to d = cam.w —
//     the camera's own Z distance directly equals Nemo's view width, no
//     extra unit conversion needed anywhere else.
//   - Roll (Nemo's cam.rot) maps to the camera's own Z Rotation, in
//     degrees (AE's native unit for rotation properties) — Nemo's
//     rot is already degrees too, no conversion needed.
//
// Keyframes are placed at Nemo's own AUTHORED camera keyframes (not
// resampled every single frame) using linear interpolation — AE has its
// own (different) bezier easing model from Nemo's [x1,y1,x2,y2] field, so
// reproducing Nemo's exact ease curve shape isn't attempted; timing
// (which frame each keyframe lands on) is exact, the in-between motion
// curve is a documented simplification the user can re-ease natively in
// AE's own graph editor after import.
//
// NOT independently tested against a real After Effects instance this
// session (time/session constraints) — the ExtendScript API calls follow
// documented AE scripting conventions (addCamera, Camera Options > Zoom,
// Transform > Position/Point of Interest/Z Rotation, setValuesAtTimes)
// but verify the first run on a throwaway comp before trusting it on real
// work.
(function(){
  function aeEscapeString(s){
    return String(s).replace(/\\/g,'\\\\').replace(/"/g,'\\"').replace(/\n/g,'\\n');
  }

  function buildCameraScript(){
    var W=state.canvasW,H=state.canvasH;
    var zoom=W; // fixed reference — see file header for why this makes d=cam.w exact
    var keys=(state.cameraKeys||[]).slice().sort(function(a,b){return a.frame-b.frame;});
    if(!keys.length)return null;

    var times=[],poi=[],pos=[],rotZ=[];
    keys.forEach(function(k){
      times.push(k.frame/state.fps);
      poi.push([k.x,k.y,0]);
      pos.push([k.x,k.y,-(k.w)]);
      rotZ.push(k.rot||0);
    });

    function jsArr(a){return '['+a.map(function(v){return typeof v==='number'?v:'['+v.join(',')+']';}).join(',')+']';}

    var lines=[];
    lines.push('// Generated by Nemo — recreates the camera move as a real, editable');
    lines.push('// After Effects camera. Run from After Effects: File > Scripts > Run Script File…');
    lines.push('// (with a composition open/selected) — or drop this file into the');
    lines.push('// ScriptUI Panels folder to run it from the Window menu instead.');
    lines.push('(function(){');
    lines.push('  var comp = app.project.activeItem;');
    lines.push('  if (!(comp && comp instanceof CompItem)) {');
    lines.push('    alert("Ouvre ou sélectionne une composition dans After Effects, puis relance ce script.");');
    lines.push('    return;');
    lines.push('  }');
    lines.push('  app.beginUndoGroup("Import caméra Nemo");');
    lines.push('  try {');
    lines.push('    var cam = comp.layers.addCamera("Nemo Camera", [comp.width/2, comp.height/2]);');
    lines.push('    cam.property("Camera Options").property("Zoom").setValue('+zoom+');');
    lines.push('    var poi = cam.property("Transform").property("Point of Interest");');
    lines.push('    var pos = cam.property("Transform").property("Position");');
    lines.push('    var rotZ = cam.property("Transform").property("Z Rotation");');
    lines.push('    var times = '+jsArr(times)+';');
    lines.push('    poi.setValuesAtTimes(times, '+jsArr(poi)+');');
    lines.push('    pos.setValuesAtTimes(times, '+jsArr(pos)+');');
    lines.push('    rotZ.setValuesAtTimes(times, '+jsArr(rotZ)+');');
    lines.push('    for (var i = 1; i <= poi.numKeys; i++) poi.setInterpolationTypeAtKey(i, KeyframeInterpolationType.LINEAR, KeyframeInterpolationType.LINEAR);');
    lines.push('    for (var i = 1; i <= pos.numKeys; i++) pos.setInterpolationTypeAtKey(i, KeyframeInterpolationType.LINEAR, KeyframeInterpolationType.LINEAR);');
    lines.push('    for (var i = 1; i <= rotZ.numKeys; i++) rotZ.setInterpolationTypeAtKey(i, KeyframeInterpolationType.LINEAR, KeyframeInterpolationType.LINEAR);');
    lines.push('    alert("Caméra Nemo importée : " + times.length + " image(s)-clé.");');
    lines.push('  } catch (e) {');
    lines.push('    alert("Échec de l\'import caméra : " + e.toString());');
    lines.push('  }');
    lines.push('  app.endUndoGroup();');
    lines.push('})();');
    return lines.join('\n');
  }

  // Best-effort: if this project was opened from a Kitsu shot, also push
  // the script as a Kitsu "working file" (see kitsu.js's pushWorkingFile
  // for why that's the right endpoint, not "output files") so whoever's
  // doing the After Effects side of the shot can pull it from Kitsu
  // instead of needing the file handed to them directly. Never blocks or
  // fails the local export — the .jsx is always saved to disk regardless
  // of whether this succeeds.
  async function pushToKitsuIfOpen(script){
    if(!(window.SMKitsu&&window.SMKitsu.isOpenedFromKitsu&&window.SMKitsu.isOpenedFromKitsu()))return null;
    try{
      var bytes=new TextEncoder().encode(script);
      var wf=await window.SMKitsu.pushWorkingFile('nemo-camera.jsx',bytes,'text/plain','After Effects','camera');
      return{ok:true,id:wf&&wf.id};
    }catch(e){
      return{ok:false,error:e&&e.message?e.message:String(e)};
    }
  }

  async function exportAECamera(opts){
    var camActive=!!(window.SMCamera&&state.cameraLayerOn&&state.cameraKeys&&state.cameraKeys.length);
    if(!camActive)return{ok:false,error:'Aucun calque caméra actif — rien à exporter.'};
    var script=buildCameraScript();
    if(!script)return{ok:false,error:'Aucune image-clé de caméra à exporter.'};

    if(exportTauriAvailable()){
      var outPath=await exportPickSaveFile('Exporter la caméra vers After Effects','nemo-camera.jsx',[{name:'ExtendScript',extensions:['jsx']}]);
      if(!outPath)return{cancelled:true};
      await exportWriteText(outPath,script);
      var kitsuRes=await pushToKitsuIfOpen(script);
      return{ok:true,path:outPath,keyCount:state.cameraKeys.length,kitsu:kitsuRes};
    }else{
      var blob=new Blob([script],{type:'text/plain'});
      var u=URL.createObjectURL(blob);var a=document.createElement('a');
      a.href=u;a.download='nemo-camera.jsx';a.click();URL.revokeObjectURL(u);
      var kitsuRes2=await pushToKitsuIfOpen(script);
      return{ok:true,browserFallback:true,keyCount:state.cameraKeys.length,kitsu:kitsuRes2};
    }
  }

  window.SMExport=window.SMExport||{};
  window.SMExport.exportAECamera=exportAECamera;
})();
